export function getProductViews(id: string, image: string): string[] {
  const suffixes = VIEW_SUFFIXES[id];
  if (!suffixes) return [image];
  const out = [image];
  for (const suffix of suffixes) {
    out.push(image.replace(/\.jpg$/, `-${suffix}.jpg`));
  }
  return out;
}
